@pytest.mark.asyncio
async def test_concurrent_cas_has_exactly_one_winner_and_audit(native):
    module, pool = native
    async with client(module) as a, client(module) as b:
        results = await asyncio.gather(put(a, selection(model="one")), put(b, selection(model="two")))
        assert sorted(r.status_code for r in results) == [200, 409]
        winner = next(r.json() for r in results if r.status_code == 200)
        assert (await a.get("/agents/worker/run-profile")).json() == winner
    async with pool.acquire() as c:
        assert await c.fetchval("SELECT count(*) FROM team_events") == 1
        assert await c.fetchval("SELECT capabilities->'run_profile'->>'revision' FROM agents WHERE project='fixture-a'") == "1"
        assert await c.fetchval("SELECT capabilities FROM agents WHERE project='fixture-b'") == "{}"


@pytest.mark.asyncio
async def test_failed_audit_has_no_committed_profile(native):
    module, pool = native
    async with pool.acquire() as c:
        await c.execute("""CREATE FUNCTION reject_event() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN RAISE EXCEPTION 'fixture audit unavailable'; END $$;
            CREATE TRIGGER reject_event BEFORE INSERT ON team_events FOR EACH ROW EXECUTE FUNCTION reject_event();""")
    async with client(module) as c:
        with pytest.raises(asyncpg.RaiseError, match="fixture audit unavailable"):
            await put(c)
    async with pool.acquire() as c:
        assert await c.fetchval("SELECT capabilities FROM agents WHERE project='fixture-a'") == "{}"
        assert await c.fetchval("SELECT count(*) FROM team_events") == 0


@pytest.mark.asyncio
async def test_label_history_and_vault_export_restore_keep_one_identity(native):
    module, pool = native
    async with client(module) as c:
        assert (await put(c)).status_code == 200
        renamed = await put(c, {}, 1, display_label="Same Label")
        assert renamed.status_code == 200, renamed.text
        async with client(module, project="fixture-b") as other:
            assert (await put(other, display_label="Same Label")).status_code == 200
            assert (await other.get("/agents/worker/run-profile")).json()["worker_id"] == "worker@fixture-b"
        history = await c.get("/agents/worker/run-profile/history")
        assert history.status_code == 200, history.text
        assert len(history.json()["history"]) == 2
        export = await c.get("/admin/projects/fixture-a/export")
        assert export.status_code == 200, export.text
        payload = export.json()
        exported = {t["table_name"]: t["rows"] for t in payload["tables"]}
        assert exported["agents"][0]["name"] == "worker"
        assert exported["agents"][0]["capabilities"]["display_name"] == "Same Label"
        assert len(exported["team_events"]) == 2
        assert exported["fixture_references"][0]["worker"] == "worker"
        async with pool.acquire() as sql:
            await sql.execute("DELETE FROM agents WHERE project='fixture-a'; DELETE FROM team_events WHERE project='fixture-a'; DELETE FROM fixture_references WHERE project='fixture-a'")
        restored = await c.post("/admin/projects/fixture-a/import", json={k: payload[k] for k in ("format", "source_project", "tables")})
        assert restored.status_code == 200, restored.text
        assert (await c.get("/agents/worker/run-profile")).json() == renamed.json()
        assert (await c.get("/agents/worker/run-profile/history")).json() == history.json()
    async with pool.acquire() as c:
        assert await c.fetchval("SELECT count(*) FROM agents WHERE project='fixture-a'") == 1
        refs = dict(await c.fetchrow("SELECT * FROM fixture_references WHERE project='fixture-a'"))
        assert refs == dict(project="fixture-a", worker="worker", claim="claimed", run="running", outbox="pending", boot="worker@fixture-a", log="worker@fixture-a")
