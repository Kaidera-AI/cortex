@pytest.fixture(scope="module")
def cluster():
    candidates = [os.environ.get("CORTEX_PROFILE_PG_BIN", ""), "/opt/homebrew/opt/postgresql@18/bin",
                  "/usr/lib/postgresql/18/bin", "/usr/lib/postgresql/17/bin", "/usr/lib/postgresql/16/bin"]
    binary = next((Path(p) for p in candidates if p and (Path(p) / "initdb").is_file()), None)
    assert binary is not None, "installed PostgreSQL binaries required for the deciding proof"
    root = Path(os.environ.get("CORTEX_PROFILE_FIXTURE_ROOT", str(API.parents[1] / "output")))
    root.mkdir(parents=True, exist_ok=True)
    # A short, owned path is needed for sockaddr_un on Mac; all state remains in root.
    directory = Path(tempfile.mkdtemp(prefix="rp-", dir=root))
    os.chmod(directory, 0o700)
    assert len(str(directory / ".s.PGSQL.5432").encode()) < 104, "choose a shorter fixture root"
    data = directory / "data"
    def run(*argv):
        p = subprocess.run([str(binary / argv[0]), *argv[1:]], capture_output=True, text=True, timeout=30)
        assert p.returncode == 0, p.stdout + p.stderr
    started = False
    try:
        run("initdb", "-D", str(data), "-U", "fixture_owner", "--auth=trust", "--no-locale", "-E", "UTF8")
        run("pg_ctl", "-D", str(data), "-l", str(directory / "server.log"), "-w", "-t", "15", "-o",
            f"-k {directory} -h '' -c max_connections=12 -c shared_buffers=16MB -c fsync=off", "start")
        started = True
        yield directory
    finally:
        if started:
            run("pg_ctl", "-D", str(data), "-m", "immediate", "-w", "-t", "15", "stop")
        # This mkdtemp is solely fixture-owned; never accepts a caller-supplied data path.
        shutil.rmtree(directory)


